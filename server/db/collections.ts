// What server/db/records.ts needs to answer PocketBase-shaped calls from
// Postgres: every collection with its PocketBase id (records keep reporting
// it as `collectionId`), its Prisma delegate, and its fields IN POCKETBASE'S
// ORDER — a record's keys come out in this order, as they did from PocketBase.
// Mirrors prisma/schema.prisma; e2e/db-schema.spec.ts fails when they drift.

export type FieldType = 'text' | 'number' | 'bool' | 'json' | 'relation' | 'file' | 'autodate';

export type FieldMeta = {
  name: string;
  type: FieldType;
  /** For a relation: the collection it points at. */
  target?: string;
  /** PocketBase refused to store this field empty. */
  required?: boolean;
  /** For a file: the largest upload PocketBase accepted, in bytes. */
  maxSize?: number;
  /** For a relation: the row goes WITH its target instead of losing the link.
   *  Only for tables born after PocketBase, which never deleted a row. */
  cascade?: boolean;
};

export type CollectionMeta = {
  name: string;
  /** PocketBase's collection id, kept as each record's `collectionId`. */
  id: string;
  /** The Prisma client property for the model (`prisma.<delegate>`). */
  delegate: string;
  fields: FieldMeta[];
};

