// The notebook's own strings. UI_STRINGS in App.tsx is module-private and has
// no placeholder convention, and the sheet lives in its own component file;
// keeping both tables here, with `satisfies`, means a key missing from one
// language fails `tsc` rather than showing up as "undefined" in a hall.
//
// The feature is called Notizblock / Notebook. Never "Notizen" alone: that
// word already labels the per-coachee notes box on the Coachees tab, and two
// things called the same with different privacy on one screen is the
// confusion this name avoids.

export type PadLang = 'DE' | 'EN';

export const fill = (s: string, v: Record<string, string | number>): string =>
  s.replace(/\{(\w+)\}/g, (_, k: string) => String(v[k] ?? ''));

